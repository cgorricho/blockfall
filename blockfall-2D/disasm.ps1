# Writes the x86-64 machine code of each BLOCKFALL edition as readable assembly:
#
#   go\asm\blockfall-go.asm      from the Go .exe     (GNU objdump + Go's line tables)
#   rust\asm\blockfall-rs.asm    from the Rust .exe   (GNU objdump + DWARF line tables)
#   csharp\asm\blockfall-cs.asm  from the .NET JIT    (the C# .exe holds IL, not x86 code)
#
# All three use Intel syntax (`mov dst, src`). Every block of instructions is
# preceded by a `;` comment naming the source line it came from, with that
# line's text, so you can read the assembly next to the code.
# Only the game's own functions are listed, not the language runtimes.
#
#   .\disasm.ps1
#
# Needs: Go, Rust (cargo), .NET 8 SDK, and GNU objdump (on PATH via WinLibs/MinGW).
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$work = Join-Path $env:TEMP 'blockfall-asm'
New-Item -ItemType Directory -Force $work | Out-Null
$env:Path = [Environment]::GetEnvironmentVariable('Path', 'Machine') + ';' + [Environment]::GetEnvironmentVariable('Path', 'User')
if (-not (Get-Command objdump -ErrorAction SilentlyContinue)) { throw 'GNU objdump not found (winget install -e --id BrechtSanders.WinLibs.POSIX.UCRT)' }

# source text per file name, for the line comments
function Read-Sources([string[]]$files) {
    $map = @{}
    foreach ($f in $files) { $map[(Split-Path $f -Leaf)] = [System.IO.File]::ReadAllLines($f) }
    $map
}
function Source-Comment($src, [string]$file, [int]$line) {
    $leaf = Split-Path $file -Leaf
    if ($src.ContainsKey($leaf) -and $line -ge 1 -and $line -le $src[$leaf].Length) {
        return ('; {0}:{1,-4} {2}' -f $leaf, $line, $src[$leaf][$line - 1].Trim())
    }
    # library code that was inlined: show a short path, no text
    $short = $file -replace '\\', '/' -replace '^.*/(library|src)/', '$1/'
    return "; [library] ${short}:$line"
}
function Write-Lines([string]$path, [System.Collections.Generic.List[string]]$lines) {
    New-Item -ItemType Directory -Force (Split-Path $path) | Out-Null
    [System.IO.File]::WriteAllLines($path, $lines, [System.Text.UTF8Encoding]::new($false))
    Write-Host ("  {0}  ({1:N0} lines)" -f $path.Substring($root.Length + 1), $lines.Count)
}

# ---------------- Go ----------------
Write-Host '== Go' -ForegroundColor Cyan
$goExe = Join-Path $work 'blockfall-go.exe'
Push-Location (Join-Path $root 'go'); go build -o $goExe .; Pop-Location

# Go's own disassembler knows the line of every instruction; GNU objdump knows Intel syntax.
$goLine = @{}
switch -Regex (go tool objdump -s '^main\.' $goExe) {
    '^\s+(\S+):(\d+)\s+0x([0-9a-f]+)\s' { $goLine[$Matches[3]] = @($Matches[1], [int]$Matches[2]) }
}
$src = Read-Sources (Get-ChildItem (Join-Path $root 'go\*.go') -Exclude '*_test.go').FullName
$out = [System.Collections.Generic.List[string]]::new()
$out.Add('; BLOCKFALL - Go edition - x86-64 machine code of package main, as found in blockfall-go.exe')
$out.Add('; Intel syntax: "mov dst, src". Generated by disasm.ps1; see README.md next to this file.')
$out.Add("; go version: $(go env GOVERSION)")
$keep = $false; $last = ''
switch -Regex (objdump -d -M intel --no-show-raw-insn $goExe) {
    '^([0-9a-f]+) <(.+)>:$' {
        $keep = $Matches[2] -like 'main.*'
        if ($keep) { $out.Add(''); $out.Add(''); $out.Add("$($Matches[2]):    ; at 0x$($Matches[1])"); $last = '' }
        continue
    }
    '^\s+([0-9a-f]+):\s+(.*)$' {
        if (-not $keep) { continue }
        $addr = $Matches[1]; $ins = $Matches[2] -replace '\s+$', ''
        if ($goLine.ContainsKey($addr)) {
            $key = "$($goLine[$addr][0]):$($goLine[$addr][1])"
            if ($key -ne $last) { $out.Add((Source-Comment $src $goLine[$addr][0] $goLine[$addr][1])); $last = $key }
        }
        $out.Add("    $addr  $ins")
    }
}
Write-Lines (Join-Path $root 'go\asm\blockfall-go.asm') $out

# ---------------- Rust ----------------
Write-Host '== Rust' -ForegroundColor Cyan
# Same release build, plus line tables (debug info does not change the generated code).
$env:CARGO_PROFILE_RELEASE_DEBUG = 'line-tables-only'
Push-Location (Join-Path $root 'rust'); cargo build --release --quiet --target-dir (Join-Path $work 'rs-target'); Pop-Location
Remove-Item Env:CARGO_PROFILE_RELEASE_DEBUG
$rsExe = Join-Path $work 'rs-target\release\blockfall.exe'

$src = Read-Sources @(Join-Path $root 'rust\src\main.rs')
$out = [System.Collections.Generic.List[string]]::new()
$out.Add('; BLOCKFALL - Rust edition - x86-64 machine code of the blockfall crate, as found in blockfall.exe (release)')
$out.Add('; Intel syntax: "mov dst, src". Generated by disasm.ps1; see README.md next to this file.')
$out.Add('; "; in fn X()" marks code of function X that the compiler inlined here.')
$out.Add("; $(rustc --version)")
$keep = $false; $last = ''; $fn = ''
switch -Regex (objdump -d -l -C -M intel --no-show-raw-insn $rsExe) {
    '^([0-9a-f]+) <(.+)>:$' {
        $keep = $Matches[2] -like '*blockfall*'
        if ($keep) { $out.Add(''); $out.Add(''); $out.Add("$($Matches[2]):    ; at 0x$($Matches[1])"); $last = ''; $fn = '' }
        continue
    }
    '^(\S.*)\(\):$' {                       # objdump: "now in (inlined) function X"
        if ($keep -and $Matches[1] -ne $fn) { $fn = $Matches[1]; $out.Add("; in fn $fn()") }
        continue
    }
    '^(\S.*):(\d+)( \(discriminator \d+\))?$' {   # objdump: "now at file:line"
        if (-not $keep) { continue }
        $key = "$($Matches[1]):$($Matches[2])"
        if ($key -ne $last) { $out.Add((Source-Comment $src $Matches[1] ([int]$Matches[2]))); $last = $key }
        continue
    }
    '^\s+([0-9a-f]+):\s+(.*)$' {
        if ($keep) { $out.Add("    $($Matches[1])  $($Matches[2] -replace '\s+$', '')") }
    }
}
Write-Lines (Join-Path $root 'rust\asm\blockfall-rs.asm') $out

# ---------------- C# ----------------
Write-Host '== C#' -ForegroundColor Cyan
# The C# .exe contains IL bytecode; x86 code only exists once the JIT compiles each
# method at run time. The runtime can print that code. Tiering off = every method
# is compiled once, fully optimised. The headless benchmark runs the game logic and
# AI, so those methods are captured; drawing code only runs in the interactive game.
$csOut = Join-Path $work 'cs'
Push-Location (Join-Path $root 'csharp')
dotnet publish -c Release -r win-x64 --self-contained false -p:PublishSingleFile=true -o $csOut --nologo -v q
Pop-Location
$jit = Join-Path $work 'cs-jit.txt'
Remove-Item $jit -ErrorAction SilentlyContinue
$env:DOTNET_TieredCompilation = '0'
$env:DOTNET_JitDisasm = 'Game:* Screen:* Program:* Term:* Piece:* Pt:* Style:* PieceDef:* Theme:* AiPlan:*'
$env:DOTNET_JitStdOutFile = $jit
& (Join-Path $csOut 'blockfall.exe') --bench 10000 --seed 42 | Out-Null
'DOTNET_TieredCompilation', 'DOTNET_JitDisasm', 'DOTNET_JitStdOutFile' | ForEach-Object { Remove-Item "Env:$_" }

$out = [System.Collections.Generic.List[string]]::new()
$out.Add('; BLOCKFALL - C# edition - x86-64 code produced by the .NET 8 JIT (RyuJIT) while running --bench')
$out.Add('; Intel syntax: "mov dst, src". Generated by disasm.ps1; see README.md next to this file.')
$out.Add('; This code is NOT inside blockfall-cs.exe: the .exe holds IL, compiled to this at run time.')
$out.Add("; dotnet $(dotnet --version)")
$out.Add('')
foreach ($l in [System.IO.File]::ReadAllLines($jit)) { $out.Add($l) }
Write-Lines (Join-Path $root 'csharp\asm\blockfall-cs.asm') $out

Write-Host 'Done.' -ForegroundColor Green
